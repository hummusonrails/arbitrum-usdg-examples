// Writes abi.ts from the forge build, so the app gets typed ABIs for the vault and the oracle.
import { readFileSync, writeFileSync } from 'node:fs';

const abi = (name) =>
    JSON.stringify(
        JSON.parse(readFileSync(`out/${name}.sol/${name}.json`, 'utf8')).abi,
        null,
        4,
    );

writeFileSync(
    'abi.ts',
    `// Generated by \`pnpm build\` from the forge output. Do not edit by hand.
export const acmeMarginVaultAbi = ${abi('AcmeMarginVault')} as const;

export const acmeOracleAbi = ${abi('AcmeOracle')} as const;
`,
);
