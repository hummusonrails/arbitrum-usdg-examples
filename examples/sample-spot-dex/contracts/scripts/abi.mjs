// Writes abi.ts from the forge build, so the app gets a typed ABI for AcmePool.
import { readFileSync, writeFileSync } from 'node:fs';

const artifact = JSON.parse(readFileSync('out/AcmePool.sol/AcmePool.json', 'utf8'));

writeFileSync(
    'abi.ts',
    `// Generated by \`pnpm build\` from the forge output. Do not edit by hand.\nexport const acmePoolAbi = ${JSON.stringify(artifact.abi, null, 4)} as const;\n`,
);
