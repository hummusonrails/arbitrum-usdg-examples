// Writes the Building with USDG on Arbitrum guide into README.md between its
// markers, from the same content the sample apps show.
import { readFileSync, writeFileSync } from 'node:fs';

import { readmeSection } from '../packages/usdg-guide/src/index.ts';

const BEGIN = '<!-- BEGIN building-with-usdg: generated by pnpm guide:readme -->';
const END = '<!-- END building-with-usdg -->';
const path = new URL('../README.md', import.meta.url);
const readme = readFileSync(path, 'utf8');
const start = readme.indexOf(BEGIN);
const end = readme.indexOf(END);

if (start === -1 || end === -1) {
    throw new Error(`README.md needs the markers:\n${BEGIN}\n${END}`);
}

writeFileSync(
    path,
    `${readme.slice(0, start + BEGIN.length)}\n\n${readmeSection()}\n${readme.slice(end)}`,
);
console.log('README.md guide section updated');
